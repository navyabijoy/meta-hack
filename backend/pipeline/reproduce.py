"""Stage 6, Reproduce: turn the replay into a Playwright test that FAILS the way the video shows.

1. Muse Spark compares the replay's final screen with the video's bug frame and
   writes assertions for the EXPECTED behaviour.
2. The test runs in the app's own repo. It counts as a reproduction only if it
   fails on an assertion (not a missing element) and the screens match.
3. If the straight replay does not show the bug, Muse Spark proposes how the
   user's actions may have differed (a double click, a rapid double submit) and
   Repro tries each hypothesis.
"""

from __future__ import annotations

import json
import re
import subprocess
from dataclasses import dataclass, field
from pathlib import Path

from backend.models import meta
from backend.pipeline import replay as replay_mod
from backend.pipeline.ingest import Ingested
from backend.pipeline.understand import parse_json
from backend.pipeline.workspace import RepoConfig, Target

TEST_DIR = "tests/repro"
VARIANTS = ["dblclick", "rapid-double-submit"]

JUDGE_PROMPT = """You are Repro's verifier. A user reported a bug with a screen recording. Repro replayed their steps in a real browser.

Bug report: {summary}
Expected: {expected}
Actual (what the user saw): {actual}

Image 1: the frame from the user's video that shows the bug.
Image 2: the final screen of Repro's replay.
Visible text of the replay's final page:
---
{text}
---

1. Does image 2 show the SAME wrong behaviour as image 1? Compare the specific symptom, not styling.
2. Write Playwright assertions that check the EXPECTED behaviour, so they FAIL on the buggy app and PASS once it is fixed.
   Use only these locator styles: page.getByText('...', {{ exact: true }}), page.getByRole('...', {{ name: '...', exact: true }}).
   Prefer counts and exact text, e.g. await expect(page.getByText('Buy milk', {{ exact: true }})).toHaveCount(1)
   Use 1-3 assertions. Each must be one line of TypeScript ending in a semicolon.

Reply with JSON only:
{{"same_bug": true, "why": "one sentence", "assertions": ["await expect(...)...;"]}}"""

HYPOTHESIS_PROMPT = """You are Repro. A replay of the user's steps did NOT reproduce their bug.

Bug: {summary}
Expected: {expected}
Actual (user saw): {actual}
Replay result: {why}

Steps replayed:
{steps}

Users often do things a video does not make obvious: double-clicking instead of clicking, or clicking twice quickly before a save finishes.
Pick up to 2 hypotheses. Each changes ONE click step to one of: {variants}.

Reply with JSON only:
{{"hypotheses": [{{"step": 6, "variant": "dblclick", "why": "..."}}]}}"""


@dataclass
class Attempt:
    variants: dict[int, str]
    replay: dict
    judge: dict
    test_path: str
    test_code: str
    run: dict
    reproduced: bool
    why: str


@dataclass
class ReproResult:
    reproduced: bool
    attempts: list[Attempt] = field(default_factory=list)
    hypotheses: list[dict] = field(default_factory=list)

    @property
    def final(self) -> Attempt | None:
        return next((a for a in self.attempts if a.reproduced), self.attempts[-1] if self.attempts else None)


def slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")[:48] or "bug"


def judge(ing: Ingested, plan: dict, rep: dict) -> dict:
    frames = {f.index: f.path for f in ing.frames}
    bug_frame = frames[plan["bug_frame"]]
    content = [
        {"type": "text", "text": JUDGE_PROMPT.format(
            summary=plan["summary"], expected=plan["expected"], actual=plan["actual"], text=rep.get("text", "")[:3000])},
        meta.image_part(bug_frame),
        meta.image_part(rep["final"]),
    ]
    return parse_json(meta.spark([{"role": "user", "content": content}], reasoning_effort="low"))


def write_test(repo: Path, plan: dict, rep: dict, assertions: list[str], name: str,
               cfg: RepoConfig | None = None) -> tuple[Path, str]:
    # Keep the replay's pacing between actions, so the test sees what the replay saw.
    lines = []
    for s in rep["steps"]:
        if s.get("code"):
            lines.append(s["code"])
            if s["action"] not in ("type",):
                lines.append("await page.waitForTimeout(700)")
    title = (plan.get("title") or plan["summary"][:60]).replace("'", "\\'")
    code = "\n".join([
        "// Generated by Repro from a screen recording. Fails while the bug exists.",
        "import { test, expect } from '@playwright/test'",
        "",
        f"test('{title}', async ({{ page }}) => {{",
        "  await page.goto('/')",
        *_fresh_state_lines(cfg),
        "",
        *[f"  {l}" for l in lines],
        "  await page.waitForTimeout(800)",
        "",
        "  // Expected behaviour from the bug report",
        *[f"  {a}" for a in assertions],
        "})",
        "",
    ])
    path = repo / (cfg.test_dir if cfg else TEST_DIR) / f"{name}.spec.ts"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(code)
    return path, code


def _fresh_state_lines(cfg: RepoConfig | None) -> list[str]:
    state = cfg.fresh_state if cfg else ["localStorage"]
    clears = {"localStorage": "localStorage.clear()", "sessionStorage": "sessionStorage.clear()"}
    calls = [clears[s] for s in state if s in clears]
    if not calls:
        return []
    return [f"  await page.evaluate(() => {{ {'; '.join(calls)} }})", "  await page.reload()"]


def run_test(repo: Path, test_path: Path | None = None, env: dict | None = None,
             cmd: str = "npx playwright test") -> dict:
    """Run one test file (or the whole suite) and summarise the result."""
    import shlex

    args = shlex.split(cmd) + ["--reporter=json"]
    if test_path:
        args.append(str(test_path.relative_to(repo)))
    proc = subprocess.run(args, cwd=repo, capture_output=True, text=True, timeout=300, env=env)
    try:
        report = json.loads(proc.stdout)
    except json.JSONDecodeError:
        return {"passed": False, "failure": "crash", "error": (proc.stderr or proc.stdout)[-1500:]}
    errors, stats = [], report.get("stats", {})
    for suite in _walk(report.get("suites", [])):
        for spec in suite.get("specs", []):
            for t in spec.get("tests", []):
                for r in t.get("results", []):
                    for e in r.get("errors", []) or ([r["error"]] if r.get("error") else []):
                        errors.append(_strip_ansi(e.get("message", "")))
    passed = stats.get("unexpected", 0) == 0 and stats.get("expected", 0) > 0
    err = "\n".join(errors)[:2000]
    failure = "none" if passed else ("assertion" if "expect(" in err and "Timeout" not in err.split("\n")[0] else "locator")
    if not passed and ("toHaveCount" in err or "Expected" in err):
        failure = "assertion"
    return {"passed": passed, "failure": failure, "error": err, "expected": stats.get("expected", 0),
            "unexpected": stats.get("unexpected", 0)}


def _walk(suites):
    for s in suites:
        yield s
        yield from _walk(s.get("suites", []))


def _strip_ansi(s: str) -> str:
    return re.sub(r"\x1b\[[0-9;]*m", "", s)


def attempt(ing: Ingested, plan: dict, grounding: list[dict], tgt: Target, out: Path,
            variants: dict[int, str], n: int, on_event=None) -> Attempt:
    emit = on_event or (lambda *a, **k: None)
    rep = replay_mod.replay(tgt.url, replay_mod.build_steps(plan, grounding, variants), out / f"replay{n}",
                            fresh_state=tgt.cfg.fresh_state)
    emit("replay", attempt=n, ok=rep.get("ok"), steps=rep.get("steps"), variants=variants, final=rep.get("final"))
    if not rep.get("ok"):
        return Attempt(variants, rep, {}, "", "", {}, False, "replay could not complete the steps")
    j = judge(ing, plan, rep)
    emit("judge", attempt=n, **j)
    name = slug(plan.get("title") or plan["summary"])
    path, code = write_test(tgt.repo, plan, rep, j.get("assertions", []), name, tgt.cfg)
    run = run_test(tgt.repo, path, tgt.env, tgt.cfg.test)
    emit("test", attempt=n, path=str(path), code=code, **run)
    reproduced = (not run["passed"]) and run["failure"] == "assertion" and bool(j.get("same_bug"))
    if reproduced:
        why = "test fails on the expected behaviour, and the replay matches the video's bug frame"
    elif run["passed"]:
        why = "replay did not show the bug: the test passed"
    elif not j.get("same_bug"):
        why = f"replay screen differs from the video: {j.get('why', '')}"
    else:
        why = f"test failed for the wrong reason ({run['failure']})"
    return Attempt(variants, rep, j, str(path), code, run, reproduced, why)


def run(ing: Ingested, plan: dict, grounding: list[dict], tgt: Target, out: Path, on_event=None) -> ReproResult:
    emit = on_event or (lambda *a, **k: None)
    result = ReproResult(False)
    a = attempt(ing, plan, grounding, tgt, out, {}, 1, on_event)
    result.attempts.append(a)
    if a.reproduced:
        result.reproduced = True
        return result

    if not a.replay.get("ok"):
        # The replay could not find or act on an element. Guessing how the user behaved
        # cannot help; report exactly where the replay stopped instead.
        failed = next((s for s in a.replay.get("steps", []) if not s.get("ok")), {})
        a.why = f"replay stopped at step {failed.get('id', '?')}: {failed.get('error') or a.replay.get('error') or 'driver error'}"
        return result

    # Hypotheses: how might the user's actions have differed from what the video shows?
    clicks = [s for s in plan["steps"] if s["action"] in ("click", "check", "dblclick")]
    steps_txt = "\n".join(f'{s["id"]}. {s["action"]} {s["target"].get("name")}' for s in plan["steps"])
    h = parse_json(meta.spark([{"role": "user", "content": HYPOTHESIS_PROMPT.format(
        summary=plan["summary"], expected=plan["expected"], actual=plan["actual"], why=a.why,
        steps=steps_txt, variants=", ".join(VARIANTS))}], reasoning_effort="low"))
    hyps = [x for x in h.get("hypotheses", []) if x.get("variant") in VARIANTS
            and any(c["id"] == x.get("step") for c in clicks)][:2]
    result.hypotheses = hyps
    emit("hypotheses", hypotheses=hyps)
    for n, hyp in enumerate(hyps, start=2):
        a = attempt(ing, plan, grounding, tgt, out, {int(hyp["step"]): hyp["variant"]}, n, on_event)
        result.attempts.append(a)
        if a.reproduced:
            result.reproduced = True
            break
    return result
